// Shared result codes for task 189. Append-only: each converted function's codes register here.
export const RESULT_CODE_NAMES: Record<number, string> = {};
// Registers a code so a printed result shows its name, never a bare integer.
export function code(value: number, name: string): number {
    if (RESULT_CODE_NAMES[value] !== undefined) throw new Error(`result code ${value} already taken by ${RESULT_CODE_NAMES[value]}`);
    RESULT_CODE_NAMES[value] = name;
    return value;
}
export function resultCodeName(value: number): string {
    const name = RESULT_CODE_NAMES[value];
    if (name === undefined) throw new Error(`unknown result code ${value}`);
    return name;
}
